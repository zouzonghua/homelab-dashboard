import { expect, test } from '@playwright/test'

let originalConfig

test.beforeEach(async ({ page }) => {
  originalConfig = await (await page.request.get('/api/v1/export')).json()
})

test.afterEach(async ({ page }) => {
  const response = await page.request.put('/api/v1/import', { data: originalConfig })
  expect(response.ok()).toBe(true)
})

test('opens shortcut help, traps focus and supports toolbar actions', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('button', { name: 'Keyboard shortcuts (?)' })).toBeVisible()
  const helpButton = page.getByRole('button', { name: 'Keyboard shortcuts (?)' })
  await helpButton.focus()
  await page.keyboard.press('?')
  const help = page.getByRole('dialog', { name: 'Keyboard shortcuts' })
  await expect(help).toBeVisible()
  const close = page.getByRole('button', { name: 'Close keyboard shortcuts' })
  await expect(close).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(close).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  await expect(close).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(helpButton).toBeFocused()

  await page.keyboard.press('e')
  await expect(page.getByRole('button', { name: 'Exit edit mode' })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: 'Enter edit mode' })).toBeVisible()
  await page.keyboard.press('v')
  await expect(page.locator('.chassis-rack')).toHaveAttribute('data-layout', 'horizontal')
  await page.keyboard.press('t')
  await expect(page.getByRole('button', { name: 'Current theme: Light. Click to switch to Dark' })).toBeVisible()

  await page.keyboard.press('g')
  await expect(page.getByRole('dialog', { name: 'Activity log' })).toBeVisible()
  const refresh = page.waitForResponse((response) => response.url().includes('/api/v1/audit-logs') && response.ok())
  await page.keyboard.press('r')
  await refresh
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  const download = page.waitForEvent('download')
  await page.keyboard.press('o')
  expect((await download).suggestedFilename()).toContain('.json')
  const chooser = page.waitForEvent('filechooser')
  await page.keyboard.press('i')
  await chooser
})

test('supports keyboard item editing without firing shortcuts while typing', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('button', { name: 'Keyboard shortcuts (?)' })).toBeVisible()
  await page.keyboard.press('a')
  const name = page.getByLabel('Category name')
  await expect(name).toBeFocused()
  await page.keyboard.press('Control+Enter')
  await expect(page.getByRole('dialog', { name: 'Add category' })).toBeVisible()
  await name.pressSequentially('Keyboard ? e v i o')
  await expect(page.getByRole('dialog', { name: 'Keyboard shortcuts' })).toHaveCount(0)
  await expect(page.locator('.chassis-edit-bar')).toBeVisible()
  await name.fill('Keyboard category')
  await page.keyboard.press('Meta+Enter')
  const group = page.locator('[data-category-name="Keyboard category"]')
  const heading = group.locator('h2')
  await expect(heading).toBeVisible()
  await heading.focus()
  await page.keyboard.press('n')
  await expect(page.getByLabel('Name', { exact: true })).toBeFocused()
  await page.getByLabel('Name', { exact: true }).fill('Keyboard service')
  await page.getByLabel('URL', { exact: true }).fill('https://keyboard.example')
  await page.keyboard.press('Control+Enter')
  const service = page.getByRole('button', { name: 'Visit Keyboard service', exact: true })
  await expect(service).toBeVisible()
  await service.focus()
  await page.keyboard.press('r')
  await expect(page.getByRole('dialog', { name: 'Edit service' })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(service).toBeFocused()
  await page.keyboard.press('d')
  const confirmation = page.getByRole('alertdialog', { name: 'Confirm deletion' })
  await expect(confirmation).toBeVisible()
  await confirmation.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(service).toBeFocused()
  await page.keyboard.press('d')
  await confirmation.getByRole('button', { name: 'Delete', exact: true }).click()
  await expect(service).toHaveCount(0)
  await heading.focus()
  await page.keyboard.press('r')
  await expect(page.getByRole('dialog', { name: 'Edit category' })).toBeVisible()
  await page.keyboard.press('Control+Shift+Delete')
  await confirmation.getByRole('button', { name: 'Delete', exact: true }).click()
  await expect(group).toHaveCount(0)
})

test('navigates and reorders groups and services with the keyboard', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('button', { name: 'Keyboard shortcuts (?)' })).toBeVisible()
  await page.keyboard.press('Home')
  const media = page.locator('[data-category-name="Media"]')
  await expect(media.locator('h2')).toBeFocused()
  await page.keyboard.press('j')
  const jellyfin = page.getByRole('button', { name: 'Visit Jellyfin', exact: true })
  await expect(jellyfin).toBeFocused()
  await page.keyboard.press('e')
  await page.keyboard.press('Alt+ArrowDown')
  await expect(media.locator('.drive-bay__name').first()).toHaveText('Navidrome')
  await expect.poll(async () => (await (await page.request.get('/api/v1/export')).json()).items.find((item) => item.name === 'Media').list.slice(0, 2).map((item) => item.name)).toEqual(['Navidrome', 'Jellyfin'])
  await expect(jellyfin).toBeFocused()
  await page.keyboard.press('Alt+ArrowUp')
  await expect(media.locator('.drive-bay__name').first()).toHaveText('Jellyfin')
  await expect.poll(async () => (await (await page.request.get('/api/v1/export')).json()).items.find((item) => item.name === 'Media').list.slice(0, 2).map((item) => item.name)).toEqual(['Jellyfin', 'Navidrome'])
  await media.locator('h2').focus()
  await page.keyboard.press('Alt+ArrowDown')
  await expect(page.locator('.rack-section').first()).toHaveAttribute('data-category-name', 'Services')
  await expect.poll(async () => (await (await page.request.get('/api/v1/export')).json()).items[0].name).toBe('Services')
  await page.reload()
  await expect(page.locator('.rack-section').first()).toHaveAttribute('data-category-name', 'Services')
})


test('supports drag-handle keyboard sorting without opening a service', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('button', { name: 'Keyboard shortcuts (?)' })).toBeVisible()
  await page.keyboard.press('e')
  const media = page.locator('[data-category-name="Media"]')
  const handle = page.getByRole('button', { name: 'Visit Jellyfin', exact: true }).locator('.drive-bay__logo')
  const popups = []
  page.on('popup', (popup) => popups.push(popup))
  await handle.focus()
  await page.keyboard.press('?')
  await expect(page.getByRole('dialog', { name: 'Keyboard shortcuts' })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(handle).toBeFocused()
  await page.keyboard.press('Space')
  await expect(handle).toHaveAttribute('aria-pressed', 'true')
  // The keyboard sensor attaches its document listener on the next frame.
  await page.evaluate(() => new Promise((resolve) => requestAnimationFrame(() => requestAnimationFrame(resolve))))
  const originalY = (await handle.boundingBox()).y
  await page.keyboard.press('ArrowDown')
  await expect.poll(async () => (await handle.boundingBox()).y).toBeGreaterThan(originalY + 5)
  await page.keyboard.press('Space')
  await expect(handle).not.toHaveAttribute('aria-pressed', 'true')
  await expect(media.locator('.drive-bay__name').first()).toHaveText('Navidrome')
  expect(popups).toHaveLength(0)
  await expect.poll(async () => (await (await page.request.get('/api/v1/export')).json()).items.find((item) => item.name === 'Media').list.slice(0, 2).map((item) => item.name)).toEqual(['Navidrome', 'Jellyfin'])
  await page.reload()
  await expect(media.locator('.drive-bay__name').first()).toHaveText('Navidrome')
})
